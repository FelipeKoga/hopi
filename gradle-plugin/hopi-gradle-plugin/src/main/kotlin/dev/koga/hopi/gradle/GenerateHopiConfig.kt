package dev.koga.hopi.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes the `hopi { }` block into the app as `dev.koga.hopi.android.generated.HopiGeneratedConfig`,
 * a Java subclass of hopi-core's `HopiConfigValues` whose constructor passes the global settings,
 * then the tool list, each tool constructed with its own settings: hopi-network's `NetworkTool`
 * with `network { enabled }` (the default) and hopi-perf's `PerfEntry` with
 * `perf { enabled = true }`, possibly neither. The provider reads it once and hands the list to the
 * start sequence (docs/design/android-capture.md, "Auto-start"). Every debuggable variant gets it
 * (unless `hopi { enabled = false }`), and only they depend on hopi-core and the runtimes.
 */
@CacheableTask
public abstract class GenerateHopiConfig : DefaultTask() {
    /** `network { enabled }`: the tool list names hopi-network's tool, with the three settings below. */
    @get:Input public abstract val networkPresent: Property<Boolean>

    @get:Input public abstract val okhttp: Property<Boolean>

    /** The `URL` calls of Ktor's Android engine are rewritten: its requests are recorded by the wrapper. */
    @get:Input public abstract val urlConnection: Property<Boolean>
    @get:Input public abstract val maxEntries: Property<Int>
    @get:Input public abstract val maxTotalBytes: Property<Long>
    @get:Input public abstract val maxBodyBytes: Property<Long>
    @get:Input public abstract val summaryLog: Property<Boolean>
    @get:Input public abstract val agentBridge: Property<Boolean>
    @get:Input public abstract val rules: Property<Boolean>
    @get:Input public abstract val redactedHeaders: ListProperty<String>
    @get:Input public abstract val redactedQueryParameters: ListProperty<String>
    @get:Input public abstract val redactionDisabled: Property<Boolean>

    /** `perf { enabled = true }`: the tool list names hopi-perf's tool. */
    @get:Input public abstract val perfPresent: Property<Boolean>

    /** A bit set, one bit per monitor in `HopiMonitor` order, which `PerfEntry` decodes. */
    @get:Input public abstract val perfAutoStart: Property<Int>
    @get:Input public abstract val perfHangThresholdMs: Property<Long>
    @get:Input public abstract val perfHangHeartbeat: Property<Boolean>

    /** `perf { remoteControl }`: false refuses the bridge's perf starts and stops. */
    @get:Input public abstract val perfRemoteControl: Property<Boolean>

    @get:OutputDirectory
    public abstract val outputDirectory: DirectoryProperty

    @TaskAction
    public fun generate() {
        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        val directory = root.resolve("dev/koga/hopi/android/generated")
        directory.mkdirs()
        directory.resolve("HopiGeneratedConfig.java").writeText(render())
    }

    internal fun render(): String = buildString {
        appendLine("package dev.koga.hopi.android.generated;")
        appendLine()
        appendLine("/** Generated by the dev.koga.hopi Gradle plugin from the app's hopi { } block. */")
        appendLine("public final class HopiGeneratedConfig extends dev.koga.hopi.android.internal.HopiConfigValues {")
        appendLine("    public HopiGeneratedConfig() {")
        appendLine("        super(")
        appendLine("            ${maxEntries.get()}, // maxEntries")
        appendLine("            ${maxTotalBytes.get()}L, // maxTotalBytes")
        appendLine("            ${maxBodyBytes.get()}L, // maxBodyBytes")
        appendLine("            ${summaryLog.get()}, // summaryLog")
        appendLine("            ${agentBridge.get()}, // agentBridge")
        appendLine("            ${redactionDisabled.get()}, // redactionDisabled")
        appendLine("            new String[] ${javaStrings(redactedHeaders.get())}, // redactHeaders")
        // The tool list (the constructor's varargs): a new tool is one more element, never a parameter.
        // Each tool is an expression and its comment; the list may be empty, and a comma follows an
        // argument only when another one does (javac refuses `, )`).
        val tools = ArrayList<Pair<String, String>>(2)
        if (networkPresent.get()) {
            tools += "new dev.koga.hopi.android.internal.NetworkTool(${okhttp.get()}, ${urlConnection.get()}, ${rules.get()})" to
                "okhttp, urlConnection, rules"
        }
        if (perfPresent.get()) {
            tools += "new dev.koga.hopi.perf.internal.PerfEntry(${perfAutoStart.get()}, ${perfHangThresholdMs.get()}L, " +
                "${perfHangHeartbeat.get()}, ${perfRemoteControl.get()})" to "perf { }: autoStart, hangThresholdMs, hangHeartbeat, remoteControl"
        }
        appendLine("            new String[] ${javaStrings(redactedQueryParameters.get())}${if (tools.isEmpty()) "" else ","} // redactQueryParameters")
        for ((index, tool) in tools.withIndex()) {
            appendLine("            ${tool.first}${if (index < tools.lastIndex) "," else ""} // ${tool.second}")
        }
        appendLine("        );")
        appendLine("    }")
        appendLine("}")
    }

    private fun javaStrings(values: List<String>): String = values.joinToString(", ", "{ ", " }") { value ->
        "\"" + value.flatMap { c ->
            when {
                c == '"' || c == '\\' -> listOf('\\', c)
                c.code < 0x20 || c.code > 0x7E -> "\\u%04x".format(c.code).toList()
                else -> listOf(c)
            }
        }.joinToString("") + "\""
    }
}
