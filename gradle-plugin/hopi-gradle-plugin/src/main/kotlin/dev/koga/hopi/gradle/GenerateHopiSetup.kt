package dev.koga.hopi.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes `dev.koga.hopi.setup.HopiSetup` into a KMP module's `iosMain` (a generated source
 * directory), the iOS app's one call, `HopiSetup.shared.start()` from Swift, the same in every
 * configuration: with [runtime] (a Debug build, whose iOS compilations get `hopi-start`) its
 * `start()` runs `dev.koga.hopi.start.Hopi.start` with the `hopi { }` block's values; without it,
 * `start()` does nothing and names no Hopi type, so a Release framework has `HopiSetup` and no
 * runtime. Public, because the module may use explicit API mode, and the framework declares it.
 */
@CacheableTask
public abstract class GenerateHopiSetup : DefaultTask() {
    /** A Debug build: `start()` starts Hopi. */
    @get:Input public abstract val runtime: Property<Boolean>
    @get:Input public abstract val maxEntries: Property<Int>
    @get:Input public abstract val maxTotalBytes: Property<Long>
    @get:Input public abstract val maxBodyBytes: Property<Long>
    @get:Input public abstract val summaryLog: Property<Boolean>
    @get:Input public abstract val agentBridge: Property<Boolean>

    /** `network { rules }`: `HopiStartConfig.rules`. */
    @get:Input public abstract val rules: Property<Boolean>
    @get:Input public abstract val redactedHeaders: ListProperty<String>
    @get:Input public abstract val redactedQueryParameters: ListProperty<String>
    @get:Input public abstract val redactionDisabled: Property<Boolean>

    /** `perf { enabled }`: `HopiStartConfig.perf`. */
    @get:Input public abstract val perf: Property<Boolean>

    /** `perf { remoteControl }`: `HopiStartConfig.perfRemoteControl`. */
    @get:Input public abstract val perfRemoteControl: Property<Boolean>

    @get:OutputDirectory
    public abstract val outputDirectory: DirectoryProperty

    @TaskAction
    public fun generate() {
        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        val directory = root.resolve("dev/koga/hopi/setup")
        directory.mkdirs()
        directory.resolve("HopiSetup.kt").writeText(render())
    }

    internal fun render(): String = buildString {
        appendLine("package dev.koga.hopi.setup")
        appendLine()
        if (!runtime.get()) {
            appendLine("/**")
            appendLine(" * Generated by the io.github.felipekoga.hopi Gradle plugin. This build has no Hopi runtime (Xcode's Release")
            appendLine(" * configuration, a build outside Xcode without `-Phopi.enabled=true`, `-Phopi.enabled=false`, or")
            appendLine(" * `hopi { enabled = false }`), so [start] does nothing.")
            appendLine(" */")
            appendLine("public object HopiSetup {")
            appendLine("    /** Does nothing in this build; in a Debug build it starts Hopi. Swift: `HopiSetup.shared.start()`. */")
            appendLine("    public fun start() {")
            appendLine("    }")
            appendLine("}")
            return@buildString
        }
        appendLine("/** Generated by the io.github.felipekoga.hopi Gradle plugin from this module's `hopi { }` block, for a Debug build. */")
        appendLine("public object HopiSetup {")
        appendLine("    /**")
        appendLine("     * Starts Hopi with this module's `hopi { }` block: URLSession capture of the whole process, the rules")
        appendLine("     * and performance runtimes, the bridge with `agentBridge`. Call it once, first thing, before any request")
        appendLine("     * (Swift: `HopiSetup.shared.start()`); idempotent. A Release build's `start()` does nothing.")
        appendLine("     */")
        appendLine("    public fun start() {")
        appendLine("        dev.koga.hopi.start.Hopi.start {")
        appendLine("            maxEntries = ${maxEntries.get()}")
        appendLine("            maxTotalBytes = ${maxTotalBytes.get()}L")
        appendLine("            maxBodyBytes = ${maxBodyBytes.get()}L")
        appendLine("            summaryLog = ${summaryLog.get()}")
        appendLine("            agentBridge = ${agentBridge.get()}")
        appendLine("            rules = ${rules.get()}")
        appendLine("            perf = ${perf.get()}")
        appendLine("            perfRemoteControl = ${perfRemoteControl.get()}")
        redactedHeaders.get().takeIf { it.isNotEmpty() }?.let { appendLine("            redactHeaders(${kotlinStrings(it)})") }
        redactedQueryParameters.get().takeIf { it.isNotEmpty() }?.let { appendLine("            redactQueryParameters(${kotlinStrings(it)})") }
        if (redactionDisabled.get()) appendLine("            unsafeDisableRedaction()")
        appendLine("        }")
        appendLine("    }")
        appendLine("}")
    }

    /** Kotlin string literals: `"`, `\` and `$` escaped, anything outside printable ASCII as `\uXXXX`. */
    private fun kotlinStrings(values: List<String>): String = values.joinToString(", ") { value ->
        "\"" + value.map { c ->
            when {
                c == '"' || c == '\\' || c == '$' -> "\\$c"
                c.code < 0x20 || c.code > 0x7E -> "\\u%04x".format(c.code)
                else -> c.toString()
            }
        }.joinToString("") + "\""
    }
}
